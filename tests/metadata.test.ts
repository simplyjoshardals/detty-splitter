import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  OG_IMAGE_PATH,
  OG_IMAGE_SIZE,
  OG_LOCALE,
  SITE_DESCRIPTION,
  SITE_NAME,
  SITE_TITLE,
  SITE_URL,
  THEME_COLOR,
  X_HANDLE,
} from "@/config";

/**
 * Guards the link preview and icons (T10.2, REQUIREMENTS D4/M10). Plain Node, no DOM. The
 * preview is fetched by WhatsApp's and X's crawlers, so what matters is that the files exist, are
 * real PNGs of the declared size, and stay small enough to be fetched. It cannot prove how a chat
 * app renders them: that is the manual paste test in BUILD_PLAN T10.2.
 */
const ROOT = new URL("../", import.meta.url);

/** WhatsApp is commonly reported to skip large preview images; ~300 KB is the usual advice (not verified). */
const MAX_OG_BYTES = 300 * 1024;

const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

function readPng(relativePath: string): { width: number; height: number; bytes: number } {
  const data = readFileSync(new URL(relativePath, ROOT));
  expect(data.subarray(0, 8).equals(PNG_SIGNATURE), `${relativePath} is not a PNG`).toBe(true);
  // IHDR: width and height are the two big-endian 32-bit values at bytes 16 and 20.
  return { width: data.readUInt32BE(16), height: data.readUInt32BE(20), bytes: data.length };
}

describe("page metadata", () => {
  it("has a title and description in place of the create-next-app text", () => {
    expect(SITE_TITLE.trim().length).toBeGreaterThan(0);
    expect(SITE_TITLE.length).toBeLessThanOrEqual(70);
    expect(SITE_DESCRIPTION.trim().length).toBeGreaterThan(0);
    expect(SITE_NAME.trim().length).toBeGreaterThan(0);
    for (const text of [SITE_TITLE, SITE_DESCRIPTION]) {
      expect(text).not.toMatch(/create next app|generated by/i);
    }
  });

  it("keeps the description short enough that chat apps do not cut it mid-sentence", () => {
    expect(SITE_DESCRIPTION.length).toBeLessThanOrEqual(160);
  });

  it("uses an https site URL that is a bare origin, so metadataBase resolves paths correctly", () => {
    const url = new URL(SITE_URL);
    expect(url.protocol).toBe("https:");
    expect(url.origin).toBe(SITE_URL);
  });

  it("is wired into the layout (layout.tsx pulls in next/font, so its source is checked, not imported)", () => {
    const layout = readFileSync(new URL("app/layout.tsx", ROOT), "utf8");
    for (const needle of [
      "metadataBase",
      "SITE_TITLE",
      "SITE_DESCRIPTION",
      "OG_IMAGE_PATH",
      "summary_large_image",
      "canonical",
      "OG_LOCALE",
      "X_HANDLE",
      "THEME_COLOR",
    ]) {
      expect(layout, `layout.tsx should mention ${needle}`).toContain(needle);
    }
  });
});

describe("preview and browser hints", () => {
  it("has an X handle in the form X accepts (@ and 1 to 15 letters, digits or underscores)", () => {
    expect(X_HANDLE).toMatch(/^@\w{1,15}$/);
  });

  it("has an og:locale in the ll_CC format", () => {
    expect(OG_LOCALE).toMatch(/^[a-z]{2}_[A-Z]{2}$/);
  });

  it("sets the browser toolbar colour to the danfo token, so the two cannot drift apart", () => {
    const css = readFileSync(new URL("app/globals.css", ROOT), "utf8");
    const danfo = /--danfo:\s*(#[0-9a-f]{6})/i.exec(css);
    if (danfo === null || danfo[1] === undefined) throw new Error("globals.css has no --danfo");
    expect(THEME_COLOR.toLowerCase()).toBe(danfo[1].toLowerCase());
  });
});

describe("og-image.png", () => {
  it("is served from public/ at a root-relative path", () => {
    expect(OG_IMAGE_PATH.startsWith("/")).toBe(true);
  });

  it("is a real PNG of the declared size", () => {
    const { width, height } = readPng(`public${OG_IMAGE_PATH}`);
    expect({ width, height }).toEqual(OG_IMAGE_SIZE);
  });

  it("is small enough for WhatsApp to fetch", () => {
    expect(readPng(`public${OG_IMAGE_PATH}`).bytes).toBeLessThanOrEqual(MAX_OG_BYTES);
  });
});

describe("icons (found by file name in app/)", () => {
  it("has a square SVG icon", () => {
    const svg = readFileSync(new URL("app/icon.svg", ROOT), "utf8");
    expect(svg).toMatch(/viewBox="0 0 64 64"/);
  });

  it("has an .ico with a 16px frame, because crawlers and old browsers ask for /favicon.ico", () => {
    const ico = readFileSync(new URL("app/favicon.ico", ROOT));
    expect(ico.readUInt16LE(0)).toBe(0); // reserved
    expect(ico.readUInt16LE(2)).toBe(1); // type: icon
    const frames = ico.readUInt16LE(4);
    const widths = Array.from({ length: frames }, (_, i) => ico.readUInt8(6 + 16 * i));
    expect(widths).toContain(16);
  });

  it("has a 180px apple-touch icon", () => {
    const { width, height } = readPng("app/apple-icon.png");
    expect({ width, height }).toEqual({ width: 180, height: 180 });
  });
});
